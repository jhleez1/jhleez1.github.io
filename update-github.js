/* Saves a snapshot of real GitHub stats into github-snapshot.js.
   The site shows live stats when it can reach GitHub; when it can't,
   it falls back to this snapshot (never to made-up numbers).

   Run it again whenever you want to refresh the snapshot:
       node update-github.js
   Needs Node.js 18 or newer. Reads the username from data.js. */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const dir = __dirname;
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(dir, "data.js"), "utf8"), sandbox);
const user = sandbox.window.PORTFOLIO.github;
if (!user) { console.error("Set github: \"username\" in data.js first."); process.exit(1); }

const headers = { "User-Agent": "portfolio-snapshot", Accept: "application/vnd.github+json" };
const get = async (url) => {
  const r = await fetch(url, { headers });
  if (!r.ok) throw new Error(`${r.status} for ${url}`);
  return r.json();
};

(async () => {
  console.log(`Fetching GitHub data for ${user}…`);
  const u = await get(`https://api.github.com/users/${user}`);
  const repos = (await get(`https://api.github.com/users/${user}/repos?per_page=100&sort=pushed`)).filter((r) => !r.fork);
  const langs = {};
  for (const r of repos.slice(0, 20)) {
    try { langs[r.name] = await get(`https://api.github.com/repos/${user}/${r.name}/languages`); } catch { langs[r.name] = {}; }
  }
  const contrib = await get(`https://github-contributions-api.jogruber.de/v4/${user}?y=all`);
  let events = [];
  try { events = await get(`https://api.github.com/users/${user}/events/public?per_page=40`); } catch { /* optional */ }

  const snap = {
    fetchedAt: new Date().toISOString(),
    user: { login: u.login, url: u.html_url, created: u.created_at, repos: u.public_repos, followers: u.followers, following: u.following },
    repos: repos.map((r) => ({ name: r.name, description: r.description, url: r.html_url, language: r.language, stars: r.stargazers_count, forks: r.forks_count, created: r.created_at, pushed: r.pushed_at, languages: langs[r.name] || {} })),
    days: contrib.contributions.filter((d) => d.date <= new Date().toISOString().slice(0, 10)).map((d) => [d.date, d.count]).filter((d) => d[1] > 0),
    firstDay: contrib.contributions.length ? contrib.contributions.map((d) => d.date).sort()[0] : null,
    events
  };
  fs.writeFileSync(path.join(dir, "github-snapshot.js"),
    "/* Generated by update-github.js - do not edit by hand. */\nwindow.GITHUB_SNAPSHOT = " + JSON.stringify(snap, null, 1) + ";\n");
  console.log(`Saved: ${snap.repos.length} repos, ${snap.days.reduce((a, d) => a + d[1], 0)} contributions.`);
})().catch((e) => { console.error("Failed:", e.message); process.exit(1); });
